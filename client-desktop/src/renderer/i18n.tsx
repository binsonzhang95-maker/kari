const messages: Record<AppLanguage, Record<I18nKey, string>> = {
  'zh-CN': baseMessages['zh-CN'],
  'en-US': baseMessages['en-US'],
  'ja-JP': jaJPMessages,
};

interface I18nContextValue {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => void;
  t: (key: I18nKey, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function detectSystemLanguage(): AppLanguage {
  const languageList = typeof navigator !== 'undefined' && navigator.languages?.length
    ? navigator.languages
    : (typeof navigator !== 'undefined' ? [navigator.language] : []);
  const primary = String(languageList.find(Boolean) || '').toLowerCase();
  if (primary.startsWith('zh')) return 'zh-CN';
  if (primary.startsWith('ja') || primary.startsWith('jp')) return 'ja-JP';
  return 'en-US';
}

export function normalizeAppLanguage(value: unknown): AppLanguage | null {
  const raw = String(value || '').trim();
  if (raw === 'zh' || raw === 'zh-CN' || raw.toLowerCase().startsWith('zh')) return 'zh-CN';
  if (raw === 'en' || raw === 'en-US' || raw.toLowerCase().startsWith('en')) return 'en-US';
  if (raw === 'ja' || raw === 'ja-JP' || raw.toLowerCase().startsWith('ja') || raw.toLowerCase().startsWith('jp')) return 'ja-JP';
  return null;
}

export function loadInitialLanguage(): AppLanguage {
  try {
    const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    const source = window.localStorage.getItem(LANGUAGE_SOURCE_STORAGE_KEY);
    const normalized = normalizeAppLanguage(stored);
    if (normalized && source === 'user') return normalized;
  } catch {
    // localStorage may be blocked in unusual renderer contexts.
  }
  return detectSystemLanguage();
}

export function persistLanguage(language: AppLanguage) {
  try {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
    window.localStorage.setItem(LANGUAGE_SOURCE_STORAGE_KEY, 'user');
  } catch {
    // Non-fatal; the current renderer session still switches language.
  }
}

export function translate(language: AppLanguage, key: I18nKey, vars?: Record<string, string | number>) {
  const lang = normalizeAppLanguage(language) || 'en-US';
  const template = messages[lang][key] || messages['en-US'][key] || key;
  if (!vars) return template;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_match: string, name: string) => String(vars[name] ?? `{${name}}`));
}

export function I18nProvider({
  children,
  language,
  setLanguage
}: {
  children: ReactNode;
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => void;
}) {
  return (
    <I18nContext.Provider value={{ language, setLanguage, t: (key, vars) => translate(language, key, vars) }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used inside I18nProvider');
  return value;
}
